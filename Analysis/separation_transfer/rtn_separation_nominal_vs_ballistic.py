#!/usr/bin/env python3
"""
rtn_separation_nominal_vs_ballistic.py
======================================

Purpose
-------
Compare deputy separation trajectories in Apophis LVLH for:

- The **guided nominal** case exported by RHIG (full rendezvous run), and
- A **pure ballistic drift** case that starts from the same initial separation
  but evolves under Hill/CW dynamics with a small random launch-velocity jitter.

The script produces two figures:

1. Figure 1 – 3×3 grid of RTN separation components for all available deputies:
   - Solid lines  : “Nominal” RHIG separation in Apophis LVLH.
   - Dashed lines : “Ballistic drift” after a small random injection jitter.
   - Dotted lines : Constant Apophis-LVLH target offsets (per deputy).

2. Figure 2 – A metrics table summarizing, for each deputy:
   - Final nominal separation norm ‖sep‖_final [m],
   - Final ballistic-drift separation norm [m],
   - Magnitude of the injected jitter ‖Δv_init‖ (1σ) [mm/s].

Inputs and data model
---------------------
The script expects, in the current directory, one or more NPZ bundles per
deputy generated by the fleet RHIG script:

- Rich bundles (full export):
    apophis_rendezvous_full_D{k}.npz

- Lightweight bundles (viz-only):
    viz_inputs_D{k}.npz

For each deputy index `idx`:

- `viz_inputs_D{idx}.npz` is preferred. It must contain:
    * `t_hist`   : time array [s],
    * `sepA_hist`: (N,3) separation in Apophis LVLH [m],
    * `rA_hist`  : (N,3) Apophis geocentric ECI positions [m],
    * `vA_hist`  : (N,3) Apophis geocentric ECI velocities [m].

- If the viz bundle is not present, the script falls back to
  `apophis_rendezvous_full_D{idx}.npz`, which must contain:
    * `t`        : time array [s],
    * `rD_N`     : deputy ECI positions [m],
    * `rA_N`     : Apophis ECI positions [m],
    * `C_A_N`    : LVLH_A<-N DCMs (rows = RTN axes in ECI).
  In this case, the Apophis LVLH separation is reconstructed as:
    sepA = C_A_N @ (rD_N − rA_N).

If no matching `viz_inputs_D*.npz` or `apophis_rendezvous_full_D*.npz` files
are found, the script exits with a message.

RTN target offsets and deployment times
---------------------------------------
- Apophis-LVLH target offsets (per deputy) are hard-coded in `DEPUTY_TARGETS_M`
  (same convention as the fleet RHIG script), in metres.

- Human-readable **deploy UTC strings** are provided in `DEPLOY_UTC` as:
    "YYYY-MM-DD HH:MM:SS Z"
  These are used purely for annotation inside the subplots and are not fed
  back into the dynamics.

Ballistic drift model
---------------------
For each deputy:

1. Extract nominal separation `sepA` in RTN and time vector `t`:
   - `tau = t − t[0]` is the time since deploy, starting at zero.

2. Estimate initial relative velocity in RTN:
      rel_v0 = (sepA[1] − sepA[0]) / dt

3. Sample a small random jitter (1σ):
      jitter ~ N(0, JITTER_SIGMA² I), where JITTER_SIGMA = 2.5e−3 m/s.

4. Compute Hill/CW ballistic drift from:
      r0 = sepA[0], v0 = rel_v0 + jitter

   using standard CW position transition matrices Φ_rr, Φ_rv:

      r_drift(t) = Φ_rr(t) r0 + Φ_rv(t) v0

   where mean motion n is derived from the Apophis LVLH frame at t₀:
      n = ‖r × v‖ / ‖r‖²  with r, v = Apophis geocentric ECI at t₀.

5. The script plots, for each RTN component (R, T, N):
   - Nominal     : sepA[:,k]          (solid, color by component),
   - Ballistic   : drift[:,k]         (dashed, same color),
   - Target line : constant DEPUTY_TARGETS_M[idx][k] (dotted).

Plots and styling
-----------------
Figure 1 (RTN components, deputies grid):

- Layout:
    * 3 rows × 3 columns (`axes = axes.ravel()`), enough for up to 9 deputies.
    * Any unused subplots are turned `axis("off")`.

- For each deputy:
    * Title: "Deputy {idx+1}".
    * Overlaid text box at the lower-right of each subplot:
          TOF: HH:MM:SS
          Deploy UTC: <from DEPLOY_UTC[idx]>
      where TOF = total τ span, formatted via `fmt_td`.

    * The grid lines:
        - Major: dashed, heavier.
        - Minor: dotted, lighter (`ax.minorticks_on()`).

    * Label crowding:
        - Only **Deputy 6** (disp == 6) explicitly keeps its x-tick labels;
          the others can be read via the shared context.

- Global:
    * `fig1.supxlabel("Time since deploy [s]")`
    * `fig1.supylabel("Separation [m]")`
    * A single legend in the upper right:
        - R, T, N nominal / drift, and one entry for “Target”.

Figure 2 (metrics table):

- Columns:
    * "Dp"                         – Deputy index (1-based).
    * "‖sep‖\n_final nom [m]"      – final nominal separation norm.
    * "‖sep‖\n_Ballistic drift [m]" – final ballistic-drift separation norm.
    * "‖Δvᵢᵢₜ‖ 1-σ\nInjection Jitter [mm/s]" – norm of jitter in mm/s.

- Rows:
    * One row per deputy, with zebra-striping for even rows.
    * Row heights controlled by `TABLE_ROW_H`.

- Title:
    * "Deputy Metrics", bold.

CLI and output
--------------
Command-line options:

- `--save` : If specified, figures are saved to `SAVE_DIR` and not shown.
             Otherwise, `plt.show()` is used.

Script behavior:

- Determines the set of deputies by scanning available `viz_inputs_D*.npz` and
  `apophis_rendezvous_full_D*.npz` files. The deputy index is taken from the
  `_D{idx}` suffix in the filename.

- If `--save` is given:
    * Creates `SAVE_DIR` (default "rtn_panels") if it does not exist.
    * Saves:
        - "rtn_components.png" – the RTN component grid (Figure 1).
        - "rtn_metrics_table.png" – the metrics table (Figure 2).
    * Prints the output directory.

- If `--save` is not given:
    * Calls `plt.show()` to display both figures.

Notes
-----
- The script assumes that deputy indices in the file names match the rows of
  `DEPUTY_TARGETS_M` and `DEPLOY_UTC` (0-based indexing: index 0 → Deputy 1).
- All dynamics here are **post hoc**: the ballistic drift is computed from the
  exported separation using CW dynamics and does not affect the nominal data.
- The jitter applied is per-deputy and seeded globally via `RAND_SEED` for
  reproducibility.
"""

from __future__ import annotations

import argparse, glob
from pathlib import Path
import matplotlib.pyplot as plt
import numpy as np
from numpy.linalg import norm

# ─────────── style & layout ───────────
BASE_FONT, TICK_FONT = 35, 30
TABLE_FONT, HEADER_FONT = 25, 25
TABLE_ROW_H = 0.2  # in-figure inches

# ─────────── constants ───────────
JITTER_SIGMA = 2.5e-3
RAND_SEED = 42
COLORS = {"R": "C0", "T": "C3", "N": "C4"}
LW_NOM, LW_DFT, LW_TGT = 2.6, 2.1, 1.4
SAVE_DIR = "rtn_panels"

# Deputy deployment → arrival → TOF (UTC)  ─ NEW ➜
DEPLOY_UTC = [
    "2029-04-13 18:05:45 Z",  # Deputy 1  (idx 0)
    "2029-04-13 14:54:45 Z",  # Deputy 2
    "2029-04-13 18:34:45 Z",  # Deputy 3
    "2029-04-13 18:25:15 Z",  # Deputy 4
    "2029-04-13 14:13:15 Z",  # Deputy 5
    "2029-04-13 17:04:45 Z",  # Deputy 6
    "2029-04-13 08:31:45 Z",  # Deputy 7
    "2029-04-13 15:19:15 Z",  # Deputy 8
]

# Apophis-LVLH target offsets (m)
DEPUTY_TARGETS_M = (
    np.array([
        [ 1.43,  2.55, -0.27], [-3.07, -0.48,  0.09],
        [ 2.39, -1.76,  0.65], [ 2.79,  1.18, -0.41],
        [-2.95, -0.72, -0.71], [-0.94,  1.83,  1.95],
        [ 1.55, -2.45,  0.68], [-0.71,  1.36, -2.30]]) * 1e3
)

np.random.seed(RAND_SEED)
plt.rcParams.update({"font.size": BASE_FONT})

# ═════════ utility functions ═════════
def hill_rate(r: np.ndarray, v: np.ndarray) -> float:
    return norm(np.cross(r, v)) / norm(r) ** 2

def cw_rr_rv(n: float, dt: float):
    c, s, nt = np.cos(n*dt), np.sin(n*dt), n*dt
    rr = np.array([[4-3*c, 0, 0], [6*(s-nt), 1, 0], [0, 0, c]])
    rv = np.array([[ s/n,  2*(1-c)/n, 0],
                   [-2*(1-c)/n, (4*s-3*nt)/n, 0],
                   [0, 0, s/n]])
    return rr, rv

def ballistic_traj(r0, v0, n, tau):
    out = np.empty((tau.size, 3))
    for i, t in enumerate(tau):
        rr, rv = cw_rr_rv(n, float(t))
        out[i] = rr @ r0 + rv @ v0
    return out

def derive_sepA(rD, rA, C):  # inertial → LVLH
    return np.einsum("nij,nj->ni", C, rD - rA)

def load_deputy(idx: int):
    viz, rich = Path(f"viz_inputs_D{idx}.npz"), Path(f"apophis_rendezvous_full_D{idx}.npz")
    if viz.exists():
        d = np.load(viz, allow_pickle=True)
        return {"t": d["t_hist"], "sepA": d["sepA_hist"],
                "rA": d["rA_hist"][0], "vA": d["vA_hist"][0]}
    if rich.exists():
        d = np.load(rich, allow_pickle=True)
        return {"t": d["t"], "sepA": derive_sepA(d["rD_N"], d["rA_N"], d["C_A_N"]),
                "rA": d["rA_N"][0], "vA": d["vA_N"][0]}
    raise FileNotFoundError

def fmt_td(sec: float) -> str:
    h, r = divmod(int(sec + .5), 3600); m, s = divmod(r, 60)
    return f"{h:02}:{m:02}:{s:02}"

# ═════════ main ═════════
def main():
    pa = argparse.ArgumentParser()
    pa.add_argument("--save", action="store_true")
    args = pa.parse_args()

    bundles = glob.glob("viz_inputs_D*.npz") + glob.glob("apophis_rendezvous_full_D*.npz")
    if not bundles:
        raise SystemExit("No NPZ bundles found.")
    deputies = sorted({int(Path(b).stem.split("_D")[-1]) for b in bundles})

    # ───────── Figure 1 ─────────
    fig1, axes = plt.subplots(3, 3, figsize=(25, 18), sharex=True, sharey=True)
    axes = axes.ravel()

    legend_h, legend_l = [], []
    table_rows = []

    for slot, idx in enumerate(deputies):
        ax = axes[slot]
        data = load_deputy(idx)

        tau = data["t"] - data["t"][0]
        dt  = tau[1]
        rel_v0 = (data["sepA"][1] - data["sepA"][0]) / dt
        jitter = np.random.normal(scale=JITTER_SIGMA, size=3)

        n = hill_rate(data["rA"], data["vA"])
        drift = ballistic_traj(data["sepA"][0], rel_v0 + jitter, n, tau)

        target = DEPUTY_TARGETS_M[idx]
        disp = idx + 1  # 1-based label

        # curves
        for k, comp in enumerate("RTN"):
            ln1, = ax.plot(tau, data["sepA"][:, k], lw=LW_NOM, color=COLORS[comp])
            ln2, = ax.plot(tau, drift[:, k],       lw=LW_DFT, ls="--", color=COLORS[comp])
            ax.hlines(target[k], tau[0], tau[-1], lw=LW_TGT, ls=":", color=COLORS[comp], alpha=.8)
            if slot == 0:
                legend_h += [ln1, ln2]
                legend_l += [f"{comp} nominal", f"{comp} drift"]
        if slot == 0:
            legend_h.append(plt.Line2D([], [], color="k", ls=":", lw=LW_TGT))
            legend_l.append("Target")

        # grid (darker)
        ax.grid(True, which="major", alpha=0.70, lw=1.2, ls="--")
        ax.grid(True, which="minor", alpha=0.35, lw=0.8, ls=":")
        ax.minorticks_on()
        ax.tick_params(axis="both", labelsize=TICK_FONT)

        ax.set_title(f"Deputy {disp}", fontsize=BASE_FONT)
        ax.set_xlabel(""); ax.set_ylabel("")

        # ── NEW ➜ add TOF + deployment UTC inside subplot ────────────────────
        text = f"TOF: {fmt_td(float(tau[-1]))}\nDeploy UTC: {DEPLOY_UTC[idx]}"
        ax.text(0.97, 0.26, text, transform=ax.transAxes,
                ha="right", va="center", linespacing=1.15,
                fontsize=BASE_FONT * 0.78,
                bbox=dict(boxstyle="round,pad=0.25", fc="white", alpha=0.85))

        # only Deputy 6 gets local x-ticks to avoid crowding
        if disp == 6:
            ax.tick_params(axis="x", labelbottom=True)

        # table metrics
        nom_mag = norm(data["sepA"], axis=1)
        drf_mag = norm(drift,       axis=1)
        table_rows.append([
            disp,
            f"{nom_mag[-1]:.3e}",    f"{drf_mag[-1]:.3e}",
            f"{norm(jitter)*1e3:.2f}"
        ])

    # hide unused panels
    for j in range(len(deputies), 9):
        axes[j].axis("off")

    # global labels + title
    fig1.supxlabel("Time since deploy [s]", fontsize=BASE_FONT, y=0.04)
    fig1.supylabel("Separation [m]",        fontsize=BASE_FONT, x=0.02)
    fig1.legend(legend_h, legend_l, loc="upper right", fontsize=BASE_FONT * 0.7)
    fig1.suptitle("Nominal vs Ballistic-Drift (RTN Components)",
                  fontsize=BASE_FONT + 5)
    plt.tight_layout(rect=[0.01, 0.03, 0.98, 0.95])

    # ───────── Figure 2 ─────────
    col_labels = [
        "Dp",
        "‖sep‖\n_final nom [m]",          # break after the metric name
        "‖sep‖\n_Ballistic drift [m]",    # ditto
        "‖Δvᵢᵢₜ‖ 1-σ\nInjection Jitter [mm/s]"
    ]


    fig2_h = TABLE_ROW_H * len(table_rows) + 0.2
    fig2, ax2 = plt.subplots(figsize=(11, fig2_h)); ax2.axis("off")

    tbl = ax2.table(cellText=table_rows, colLabels=col_labels,
                    cellLoc="center", colLoc="center", loc="center")
    tbl.auto_set_font_size(False); tbl.set_fontsize(35)
    tbl.auto_set_column_width(col=list(range(len(col_labels))))
    for j in range(len(col_labels)):
        hdr = tbl[0, j]
        hdr.set_text_props(weight="bold", color="white", fontsize=35)
        hdr.set_facecolor("#0B69B4")

    for i in range(1, len(table_rows) + 1):
        if i % 2 == 0:
            for j in range(len(col_labels)):
                tbl[i, j].set_facecolor("#F3F3F3")
        for j in range(len(col_labels)):
            tbl[i, j].set_height(TABLE_ROW_H / fig2.get_figheight())
    for j in range(len(col_labels)):
        tbl[0, j].set_height(TABLE_ROW_H / fig2.get_figheight())

    fig2.suptitle("Deputy Metrics", fontsize=BASE_FONT + 5, weight="bold")
    fig2.tight_layout(rect=[0, 0.03, 1, 0.95])

    # ───────── output ─────────
    if args.save:
        Path(SAVE_DIR).mkdir(exist_ok=True)
        fig1.savefig(Path(SAVE_DIR) / "rtn_components.png", dpi=300)
        fig2.savefig(Path(SAVE_DIR) / "rtn_metrics_table.png", dpi=300)
        print(f"Saved figures → ./{SAVE_DIR}/")
    else:
        plt.show()

if __name__ == "__main__":
    main()
